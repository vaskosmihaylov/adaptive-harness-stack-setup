#!/usr/bin/env bash
# Generate dist/CLAUDE.md and dist/AGENTS.md from the shared core in src/.
# One source of truth means the two harnesses cannot drift apart.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$ROOT/src"
DIST="$ROOT/dist"

mkdir -p "$DIST"

banner() {
  printf '<!-- Generated by adaptive-harness-stack-setup/build.sh from src/. Edit src/, not this file. -->\n\n'
}

build() {
  local name="$1" out="$2"
  {
    banner
    cat "$SRC/$name.header.md"
    printf '\n'
    cat "$SRC/core.md"
    printf '\n'
    cat "$SRC/$name.footer.md"
  } > "$out"
  printf '  %-12s -> %s (%s lines)\n' "$name" "${out#"$ROOT"/}" "$(wc -l < "$out" | tr -d ' ')"
}

echo "Building:"
build claude "$DIST/CLAUDE.md"
build codex  "$DIST/AGENTS.md"
