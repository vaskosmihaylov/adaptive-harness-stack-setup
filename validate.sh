#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

bash -n "$ROOT/build.sh" "$ROOT/install.sh" "$ROOT/validate.sh"
jq empty "$ROOT/settings/claude-settings.json"

python3 - "$ROOT" <<'PY'
import pathlib
import sys
import tomllib

root = pathlib.Path(sys.argv[1])
required = {"name", "description", "developer_instructions"}
for path in sorted((root / "agents" / "codex").glob("*.toml")):
    data = tomllib.loads(path.read_text())
    missing = required - data.keys()
    if missing:
        raise SystemExit(f"{path}: missing {', '.join(sorted(missing))}")
    if data.get("sandbox_mode") != "read-only":
        raise SystemExit(f"{path}: global utility agents must be read-only")
PY

for agent in "$ROOT"/agents/claude/*.md; do
  sed -n '1,/^---$/p' "$agent" | grep -q '^name:'
  sed -n '1,/^---$/p' "$agent" | grep -q '^description:'
  sed -n '1,/^---$/p' "$agent" | grep -q '^model:'
  sed -n '1,/^---$/p' "$agent" | grep -q '^permissionMode: plan$'
done

bash "$ROOT/build.sh"
grep -q '^<!-- Generated by adaptive-harness-stack-setup/build.sh' "$ROOT/dist/CLAUDE.md"
grep -q '^<!-- Generated by adaptive-harness-stack-setup/build.sh' "$ROOT/dist/AGENTS.md"

if [ -e "$ROOT/agents/claude/scout.md" ] || [ -e "$ROOT/agents/codex/scout.toml" ]; then
  echo "retired scout agent still present" >&2
  exit 1
fi

echo "Validation passed."
